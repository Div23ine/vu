#!/usr/bin/env node
/**
 * Scan-egress CIDR generator (Task 98).
 *
 * The scan VCN is public-egress-only: because OCI security rules are
 * allow-lists, "everything except private/reserved space" has to be spelled
 * out as an explicit list of CIDRs. This script computes that list as the
 * exact complement of the forbidden ranges — the SAME ranges the controller's
 * target guard blocks (Task 84) — with BigInt arithmetic and no libraries, so
 * the answer is exact rather than float-approximated.
 *
 * Usage:
 *   node scripts/gen-scan-egress.mjs            → verify the committed file
 *   node scripts/gen-scan-egress.mjs --write    → (re)generate it
 *
 * The generated file is COMMITTED (Terraform reads it) and CI runs the verify
 * mode, so a hand-edited list cannot drift from the algorithm.
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUTPUT_PATH = path.join(
  REPO_ROOT,
  'infra/terraform/oci/modules/network-scan/egress_cidrs.generated.tf',
);

/**
 * The ranges a scan must NEVER reach: private space (the tenancy's own VCNs,
 * every other customer's RFC1918), link-local (the instance metadata service
 * lives at 169.254.169.254), CGNAT, loopback, benchmark/documentation space,
 * benchmarking 198.18/15, multicast and reserved. Identical to the controller
 * target guard's list (Task 84).
 */
export const FORBIDDEN_CIDRS = [
  '0.0.0.0/8',
  '10.0.0.0/8',
  '100.64.0.0/10',
  '127.0.0.0/8',
  '169.254.0.0/16',
  '172.16.0.0/12',
  '192.0.0.0/24',
  '192.0.2.0/24',
  '192.168.0.0/16',
  '198.18.0.0/15',
  '198.51.100.0/24',
  '203.0.113.0/24',
  '224.0.0.0/4',
  '240.0.0.0/4',
];

const TOTAL = 1n << 32n;

export function cidrToRange(cidr) {
  const [address, bitsText] = cidr.split('/');
  const bits = BigInt(bitsText);
  if (bits < 0n || bits > 32n) throw new Error(`bad prefix in ${cidr}`);
  const octets = address.split('.').map((part) => BigInt(part));
  if (octets.length !== 4 || octets.some((octet) => octet < 0n || octet > 255n)) {
    throw new Error(`bad address in ${cidr}`);
  }
  const start = (octets[0] << 24n) | (octets[1] << 16n) | (octets[2] << 8n) | octets[3];
  const size = 1n << (32n - bits);
  if (start % size !== 0n) throw new Error(`unaligned CIDR ${cidr}`);
  return { start, end: start + size }; // end is EXCLUSIVE
}

function rangeToCidrs(start, endExclusive) {
  // Greedy largest-aligned-block decomposition of [start, endExclusive).
  const out = [];
  let cursor = start;
  while (cursor < endExclusive) {
    const remaining = endExclusive - cursor;
    // Largest block that both fits and is aligned at the cursor.
    const alignment = cursor === 0n ? 32n : bigTrailingZeros(cursor);
    let bits = minBigInt(alignment, bigLog2Floor(remaining));
    const size = 1n << BigInt(bits);
    out.push(`${ipOf(cursor)}/${32 - Number(bits)}`);
    cursor += size;
    void remaining;
  }
  return out;
}

function bigTrailingZeros(value) {
  let zeros = 0n;
  let current = value;
  while ((current & 1n) === 0n && current !== 0n) {
    current >>= 1n;
    zeros += 1n;
  }
  return zeros;
}

function bigLog2Floor(value) {
  let log = 0n;
  let current = value;
  while (current > 1n) {
    current >>= 1n;
    log += 1n;
  }
  return log;
}

function minBigInt(a, b) {
  return a < b ? a : b;
}

function ipOf(value) {
  return [
    Number((value >> 24n) & 0xffn),
    Number((value >> 16n) & 0xffn),
    Number((value >> 8n) & 0xffn),
    Number(value & 0xffn),
  ].join('.');
}

/**
 * The complement of `forbidden` inside 0.0.0.0/0 — sorted, collapsed, exact.
 * @param {string[]} forbidden
 * @returns {string[]}
 */
export function complementCidrs(forbidden = FORBIDDEN_CIDRS) {
  const ranges = forbidden.map(cidrToRange).sort((a, b) => (a.start < b.start ? -1 : 1));

  // Merge overlapping/adjacent forbidden ranges first.
  const merged = [];
  for (const range of ranges) {
    const last = merged.at(-1);
    if (last !== undefined && range.start <= last.end) {
      if (range.end > last.end) last.end = range.end;
      continue;
    }
    merged.push({ ...range });
  }

  const allowed = [];
  let cursor = 0n;
  for (const range of merged) {
    if (range.start > cursor) allowed.push(...rangeToCidrs(cursor, range.start));
    if (range.end > cursor) cursor = range.end;
  }
  if (cursor < TOTAL) allowed.push(...rangeToCidrs(cursor, TOTAL));
  return allowed;
}

export function renderTerraform(cidrs) {
  const list = cidrs.map((cidr) => `    "${cidr}",`).join('\n');
  return `# GENERATED by scripts/gen-scan-egress.mjs — DO NOT EDIT.
#
# The allow-list complement of the forbidden ranges (private, link-local,
# CGNAT, loopback, benchmark, documentation, multicast, reserved): every
# public IPv4 CIDR a scan pod may reach. OCI security rules are allow-lists,
# so "the public internet minus the private space" is exactly this list —
# ${cidrs.length} rules on the scan-egress NSG. Regenerate with:
#   node scripts/gen-scan-egress.mjs --write
locals {
  scan_egress_cidrs = [
${list}
  ]
}
`;
}

async function main() {
  const cidrs = complementCidrs();
  const rendered = renderTerraform(cidrs);
  const write = process.argv.includes('--write');
  if (write) {
    await writeFile(OUTPUT_PATH, rendered, 'utf8');
    console.log(
      `OK: gen-scan-egress wrote ${cidrs.length} CIDRs to ${path.relative(REPO_ROOT, OUTPUT_PATH)}`,
    );
    return;
  }
  let committed;
  try {
    committed = await readFile(OUTPUT_PATH, 'utf8');
  } catch {
    console.error(
      `FAIL: gen-scan-egress: ${path.relative(REPO_ROOT, OUTPUT_PATH)} is missing (run with --write)`,
    );
    process.exit(1);
  }
  if (committed !== rendered) {
    console.error(
      'FAIL: gen-scan-egress: the committed CIDR list does not match the generator (run with --write)',
    );
    process.exit(1);
  }
  console.log('OK: gen-scan-egress');
}

const invokedDirectly =
  process.argv[1] !== undefined && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (invokedDirectly) {
  await main();
}
