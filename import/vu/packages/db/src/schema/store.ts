import { sql } from 'drizzle-orm';
import {
  boolean,
  check,
  index,
  pgEnum,
  pgTable,
  smallint,
  text,
  uniqueIndex,
  uuid,
} from 'drizzle-orm/pg-core';
import { NEWSLETTER_STATUSES } from '../enum-values.js';
import { citext, idCol, timestamps, tz, usdCents } from './_columns.js';
import { invoices } from './billing.js';
import { organizations } from './identity.js';

/**
 * The public store (Task 40b): premium products, the licence entitlements a paid
 * invoice grants, and newsletter subscribers.
 *
 * Money rules are the platform's, unchanged: `price_usd_cents` is integer USD cents
 * and USD is the only settlement currency. A buyer in Nairobi is shown a locked KES
 * *display* quote (Task 33) and charged in USD; nothing here can express a non-USD
 * price.
 *
 * A licence key is the only secret this schema holds, and it is a bearer credential
 * for a download: it is unique, it is generated by the API from `crypto.randomInt`,
 * and the database refuses a key that does not match the published format.
 */

/**
 * Declared here rather than in `_enums.ts`: this task's deliverables list covers
 * `enum-values.ts` (the value tuples, which `@vunvault/contracts` builds its Zod
 * enums from) and this file, and not the shared enum module.
 */
export const newsletterStatusEnum = pgEnum('newsletter_status', NEWSLETTER_STATUSES);

/** `VV-XXXX-XXXX-XXXX-XXXX` in Crockford base32 (no I, L, O or U). */
export const LICENSE_KEY_PATTERN = '^VV-[0-9A-HJKMNP-TV-Z]{4}(-[0-9A-HJKMNP-TV-Z]{4}){3}$';

/** What a price is per: a one-off licence, a year of updates, or a rule pack. */
export const PRODUCT_UNIT_LABELS = ['license', 'year', 'pack'] as const;

export const products = pgTable(
  'products',
  {
    id: idCol(),
    /** Public URL segment, e.g. `reconvault-pro`. */
    slug: text('slug').notNull().unique(),
    name: text('name').notNull(),
    /** Display grouping, e.g. `Recon`, `Scanning`, `GRC`. */
    category: text('category').notNull(),
    description: text('description').notNull(),
    /** Three selling points, shown as a checklist on the product card. */
    features: text('features')
      .array()
      .notNull()
      .default(sql`'{}'`),
    priceUsdCents: usdCents('price_usd_cents').notNull(),
    unitLabel: text('unit_label').notNull(),
    active: boolean('active').notNull().default(true),
    /**
     * R2 key of the licensed archive. Null until an operator uploads one, which is
     * why `downloadable` is derived rather than stored: a product can be sold
     * before its archive exists.
     */
    deliveryObjectKey: text('delivery_object_key'),
    sortOrder: smallint('sort_order').notNull().default(0),
    ...timestamps,
  },
  (table) => [
    check('products_price_positive', sql`${table.priceUsdCents} > 0`),
    check('products_unit_label_allowed', sql`${table.unitLabel} IN ('license', 'year', 'pack')`),
    index('products_active_sort_idx').on(table.active, table.sortOrder),
  ],
).enableRLS();

/**
 * One licence per (organisation, product, invoice).
 *
 * The unique index is what makes granting idempotent: a webhook delivered twice, or
 * a reconciliation that replays a capture, cannot mint a second key for the same
 * purchase.
 */
export const productEntitlements = pgTable(
  'product_entitlements',
  {
    id: idCol(),
    orgId: uuid('org_id')
      .notNull()
      .references(() => organizations.id),
    productId: uuid('product_id')
      .notNull()
      .references(() => products.id),
    invoiceId: uuid('invoice_id')
      .notNull()
      .references(() => invoices.id),
    licenseKey: text('license_key').notNull().unique(),
    grantedAt: tz('granted_at').notNull().defaultNow(),
    /** "Twelve months of updates": granted_at + 12 months, set by the API. */
    updatesUntil: tz('updates_until').notNull(),
    revokedAt: tz('revoked_at'),
  },
  (table) => [
    uniqueIndex('product_entitlements_org_product_invoice_idx').on(
      table.orgId,
      table.productId,
      table.invoiceId,
    ),
    index('product_entitlements_org_id_idx').on(table.orgId),
    check(
      'product_entitlements_license_key_format',
      sql`${table.licenseKey} ~ '^VV-[0-9A-HJKMNP-TV-Z]{4}(-[0-9A-HJKMNP-TV-Z]{4}){3}$'`,
    ),
    check(
      'product_entitlements_updates_after_grant',
      sql`${table.updatesUntil} > ${table.grantedAt}`,
    ),
  ],
).enableRLS();

/**
 * Double opt-in newsletter.
 *
 * One token hash serves both the confirmation link and the unsubscribe link: a
 * subscriber who can prove they own the inbox can also leave it, and there is no
 * second secret to lose. The raw token exists only inside the email that carries it.
 */
export const newsletterSubscribers = pgTable(
  'newsletter_subscribers',
  {
    id: idCol(),
    email: citext('email').notNull().unique(),
    status: newsletterStatusEnum('status').notNull().default('pending'),
    /** SHA-256 of the single token used to confirm and to unsubscribe. */
    tokenHash: text('token_hash').notNull(),
    /** Where the signup came from, e.g. `blog`. */
    source: text('source'),
    /** Salted daily, like every other IP the platform records. Never the address. */
    ipHash: text('ip_hash'),
    confirmedAt: tz('confirmed_at'),
    unsubscribedAt: tz('unsubscribed_at'),
    ...timestamps,
  },
  (table) => [index('newsletter_subscribers_status_idx').on(table.status)],
).enableRLS();
