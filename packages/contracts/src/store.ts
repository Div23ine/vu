import { z } from 'zod';
import { IsoDateTime, Uuid, UsdCents } from './common.js';

/**
 * The public store: premium products, licence entitlements and the newsletter.
 *
 * The money rules are the platform's and do not bend here. A product is priced in
 * integer USD cents, `settlementCurrency` is the literal `"USD"`, and a purchase
 * produces an INVOICE — not a charge. The buyer then takes an FX quote for display
 * and checks out through the existing billing routes, so a licence bought in Nairobi
 * is shown in shillings and charged in dollars, exactly like a scan.
 *
 * A licence key is a bearer credential for a download. It is generated by the API,
 * stored once, and pinned by a database check to the published Crockford-base32
 * shape; the letters I, L, O and U are excluded so a key can be read aloud without
 * ambiguity.
 */

/** What a price is per. */
export const PRODUCT_UNIT_LABELS = ['license', 'year', 'pack'] as const;
export type ProductUnitLabel = (typeof PRODUCT_UNIT_LABELS)[number];

/** `VV-XXXX-XXXX-XXXX-XXXX`, Crockford base32 (no I, L, O or U). */
export const LICENSE_KEY_PATTERN = /^VV-[0-9A-HJKMNP-TV-Z]{4}(-[0-9A-HJKMNP-TV-Z]{4}){3}$/;

export const ProductView = z.object({
  id: Uuid,
  slug: z.string().min(1),
  name: z.string().min(1),
  category: z.string().min(1),
  description: z.string().min(1),
  features: z.array(z.string()),
  priceUsdCents: UsdCents,
  unitLabel: z.enum(PRODUCT_UNIT_LABELS),
  /** Always USD: a product cannot be priced in anything else. */
  settlementCurrency: z.literal('USD'),
});
export type ProductView = z.infer<typeof ProductView>;

export const PurchaseBody = z.object({
  productId: Uuid,
});
export type PurchaseBody = z.infer<typeof PurchaseBody>;

/**
 * A purchase issues an invoice and nothing more. Payment follows through
 * `POST /billing/fx-quotes` + `POST /billing/checkout` (Task 33), and the licence
 * is granted by the payment webhook (Task 34 → 40c), never by this response.
 */
export const PurchaseResponse = z.object({
  data: z.object({
    invoiceId: Uuid,
    invoiceNumber: z.string(),
    totalUsdCents: UsdCents,
    settlementCurrency: z.literal('USD'),
  }),
});
export type PurchaseResponse = z.infer<typeof PurchaseResponse>;

export const EntitlementView = z.object({
  id: Uuid,
  productId: Uuid,
  productName: z.string(),
  licenseKey: z.string().regex(LICENSE_KEY_PATTERN),
  grantedAt: IsoDateTime,
  updatesUntil: IsoDateTime,
  /** True when the product has an archive in object storage and the licence stands. */
  downloadable: z.boolean(),
});
export type EntitlementView = z.infer<typeof EntitlementView>;

export const DownloadUrlResponse = z.object({
  data: z.object({
    url: z.string().url(),
    expiresAt: IsoDateTime,
  }),
});
export type DownloadUrlResponse = z.infer<typeof DownloadUrlResponse>;

export const NewsletterSubscribeBody = z.object({
  email: z.string().email(),
  /** Where the signup came from, e.g. `blog`. */
  source: z.string().max(40).optional(),
});
export type NewsletterSubscribeBody = z.infer<typeof NewsletterSubscribeBody>;

export const NewsletterTokenBody = z.object({
  token: z.string().min(20),
});
export type NewsletterTokenBody = z.infer<typeof NewsletterTokenBody>;

